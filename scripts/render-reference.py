#!/usr/bin/env python3
"""Render the --dump-reference JSON (stdin) into the generated blocks of the
docs pages in the directory given as the argument. Called by
scripts/gen-reference.sh; see there."""
import json
import re
import sys

BEGIN = "<!-- BEGIN GENERATED: {} -->"
END = "<!-- END GENERATED -->"
NOTE = "<!-- Generated by scripts/gen-reference.sh from `nano-coder --dump-reference`; edit the code, not this block. -->"


def cell(text):
    """One Markdown table cell: no newlines, pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def code(text):
    return f"`{text}`" if text else ""


def cli(ref):
    rows = ["| Flag | Aliases | Argument | Description |", "|---|---|---|---|"]
    for f in ref["flags"]:
        rows.append("| {} | {} | {} | {} |".format(code(f["name"]), ", ".join(code(a) for a in f["aliases"]),
                                                  cell(code(f["argument"])), cell(f["description"])))
    return rows


def commands(ref):
    rows = ["| Command | Arguments | Description |", "|---|---|---|"]
    for c in ref["commands"]:
        rows.append("| {} | {} | {} |".format(code(c["name"]), cell(code(c["arguments"])), cell(c["description"])))
    return rows


def param_rows(props, required, prefix):
    """Rows for every parameter, recursing into nested objects and arrays of
    objects (`questions[].options[].label`) so the reference shows the full
    schema a call must follow."""
    rows = []
    for name, p in props.items():
        alts = [a for a in (p.get("anyOf") or p.get("oneOf") or []) if isinstance(a, dict)]
        kind = p.get("type", "") or " or ".join(alt_kind(a) for a in alts)
        if isinstance(kind, list):
            kind = " or ".join(kind)
        if "enum" in p:
            kind += ": " + ", ".join(code(e) for e in p["enum"])
        items = p.get("items") if isinstance(p.get("items"), dict) else {}
        if kind.startswith("array") and (items.get("type") or items.get("anyOf") or items.get("oneOf")):
            kind = f"array of {alt_kind(items)}"
        rows.append("| {} | {} | {} | {} |".format(code(prefix + name), cell(kind), "yes" if name in required else "no",
                                                   cell(p.get("description", ""))))
        for alt in alts:
            if alt.get("properties"):
                rows += param_rows(alt["properties"], set(alt.get("required") or []), f"{prefix}{name}.")
        for alt in [a for a in (items.get("anyOf") or items.get("oneOf") or []) if isinstance(a, dict)]:
            if alt.get("properties"):
                rows += param_rows(alt["properties"], set(alt.get("required") or []), f"{prefix}{name}[].")
        if items.get("properties"):
            rows += param_rows(items["properties"], set(items.get("required") or []), f"{prefix}{name}[].")
        if p.get("properties"):
            rows += param_rows(p["properties"], set(p.get("required") or []), f"{prefix}{name}.")
    return rows


def alt_kind(schema):
    """Type name of a schema, joining `anyOf`/`oneOf` alternatives (`string or object`)."""
    kind = schema.get("type", "")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind:
        return kind
    alts = schema.get("anyOf") or schema.get("oneOf") or []
    return " or ".join(alt_kind(a) for a in alts if isinstance(a, dict))


def tools(ref):
    out = ["| Tool | Plan mode | Summary |", "|---|---|---|"]
    for t in ref["tools"]:
        first = t["description"].split("\n")[0]
        first = re.split(r"(?<=\.)\s", first, maxsplit=1)[0]
        out.append("| [{0}](#{0}) | {1} | {2} |".format(t["name"], "yes" if t["readOnly"] else "no", cell(first)))
    for t in ref["tools"]:
        out += ["", f"### {t['name']}", "", t["description"].strip(), "",
                "Available in plan mode: " + ("yes (read-only)." if t["readOnly"] else "no."), ""]
        params = t.get("parameters") or {}
        props = params.get("properties") or {}
        required = set(params.get("required") or [])
        if not props:
            out.append("No parameters.")
            continue
        out += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
        out += param_rows(props, required, "")
    return out


def config(ref):
    rows = ["| Key | Type | Default | Description |", "|---|---|---|---|"]
    for k in ref["configKeys"]:
        rows.append("| {} | {} | {} | {} |".format(code(k["path"]), k["type"], cell(code(k["default"])),
                                                  cell(k["description"])))
    return rows


BLOCKS = {"cli.md": ("cli", cli), "commands.md": ("commands", commands), "tools.md": ("tools", tools),
          "configuration.md": ("config", config)}


def main():
    ref = json.load(sys.stdin)
    root = sys.argv[1]
    for page, (name, render) in BLOCKS.items():
        path = f"{root}/{page}"
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        begin = BEGIN.format(name)
        start = text.find(begin)
        end = text.find(END, start)
        if start < 0 or end < 0:
            sys.exit(f"render-reference: {path} has no '{begin}' ... '{END}' block")
        body = "\n".join([begin, NOTE, ""] + render(ref) + ["", ""])
        new = text[:start] + body + text[end:]
        if new != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(new)


if __name__ == "__main__":
    main()
